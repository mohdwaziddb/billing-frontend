const emptySettings: CompanyInvoiceSettings = {
  defaultTemplateId: "",
  showWatermark: false,
  watermarkText: "",
  showSignature: true,
  signatureLabel: "Authorized Signature",
  signatureHeading: "For Company",
  showQr: true,
  showBankDetails: true,
  showTerms: true,
  showNotes: true,
  noteText: "Thank you for choosing Bizio.",
  termsText: "Goods once sold will not be taken back.",
  footerCredit: "Generated by Bizio Billing SaaS"
};

// Backend CompanyInvoiceSettingsService.validateRequest jaisi hi limits.
const LIMITS = { watermarkText: 60, signatureHeading: 120, signatureLabel: 120, footerCredit: 200, noteText: 1000, termsText: 2000 } as const;

// Printable page width (CSS px) per paper size: thumbnails/preview isi par layout hote hain.
const A4_WIDTH = 794;
const A4_HEIGHT = 1123;
const PREVIEW_MIN_WIDTH = 640;
const THUMB_HEIGHT = 168;
const THUMB_CONCURRENCY = 3;

type OptionKey = keyof Omit<CompanyInvoiceSettings, "defaultTemplateId">;
const OPTION_KEYS: OptionKey[] = [
  "showWatermark", "watermarkText", "showSignature", "signatureLabel", "signatureHeading", "showQr",
  "showBankDetails", "showTerms", "showNotes", "noteText", "termsText", "footerCredit"
];

const toPreviewRequest = (value: CompanyInvoiceSettings): InvoiceTemplatePreviewRequest => ({
  showWatermark: value.showWatermark,
  watermarkText: value.watermarkText ?? undefined,
  showSignature: value.showSignature,
  signatureLabel: value.signatureLabel ?? undefined,
  signatureHeading: value.signatureHeading ?? undefined,
  showQr: value.showQr,
  showBankDetails: value.showBankDetails,
  showTerms: value.showTerms,
  showNotes: value.showNotes,
  noteText: value.noteText ?? undefined,
  termsText: value.termsText ?? undefined,
  footerCredit: value.footerCredit ?? undefined
});

const toSaveRequest = (value: CompanyInvoiceSettings, defaultTemplateId: string): CompanyInvoiceSettingsRequest => ({
  ...toPreviewRequest(value),
  defaultTemplateId
});

const paperLabel = (template: InvoiceTemplateMetadata) => template.supportedPaperSizes?.[0] ?? "A4";
const accentOf = (template: InvoiceTemplateMetadata) => template.defaultColors?.accent ?? "#0f172a";

/** Iframe me invoice HTML ka sandboxed, scaled render (gallery thumbnail / preview). */
const InvoiceFrame = ({ html, title, width, scale, height }: { html: string; title: string; width: number; scale: number; height: number }) => (
  <iframe
    title={title}
    // First-party backend HTML (template.css inlined). Fully sandboxed: no scripts, no same-origin.
    srcDoc={html}
    sandbox=""
    tabIndex={-1}
    className="pointer-events-none block border-0 bg-white"
    style={{ width, height, transform: `scale(${scale})`, transformOrigin: "top left" }}
  />
);

const printHtml = (html: string) => {
  // Sandboxed preview iframe par print() silently fail hota hai, isliye hidden same-origin iframe
  // (InvoiceDetailPage jaisa). Ye frame app origin par hai: sanitize zaroori, allowStyle se CSS rehta hai.
  const frame = document.createElement("iframe");
  frame.style.position = "fixed";
  frame.style.right = "0";
  frame.style.bottom = "0";
  frame.style.width = "0";
  frame.style.height = "0";
  frame.style.border = "0";
  frame.setAttribute("aria-hidden", "true");
  document.body.appendChild(frame);
  frame.onload = () => {
    window.setTimeout(() => {
      frame.contentWindow?.focus();
      frame.contentWindow?.print();
      window.setTimeout(() => frame.remove(), 1000);
    }, 250);
  };
  const doc = frame.contentWindow?.document;
  if (!doc) {
    frame.remove();
    notificationService.showError("Unable to open print preview right now.");
    return;
  }
  doc.open();
  doc.write(sanitizeHtml(html, { allowStyle: true }));
  doc.close();
};

export const InvoiceTemplatesPage = () => {
  // Backend: list/settings = VIEW, preview = PREVIEW, default + options save = CHANGE_DEFAULT.
  const { can } = useAuth();
  const canChangeDefault = can("INVOICE_TEMPLATES", "CHANGE_DEFAULT");
  const canPreview = can("INVOICE_TEMPLATES", "PREVIEW");
  const { setApiError, clearMessage } = useApiMessage();
  const [templates, setTemplates] = useState<InvoiceTemplateMetadata[]>([]);
  const [savedSettings, setSavedSettings] = useState<CompanyInvoiceSettings>(emptySettings);
  const [settings, setSettings] = useState<CompanyInvoiceSettings>(emptySettings);
  const [selectedTemplateId, setSelectedTemplateId] = useState("");
  const [loading, setLoading] = useState(true);
  const [loadError, setLoadError] = useState(false);
  const [savingOptions, setSavingOptions] = useState(false);
  const [settingDefaultId, setSettingDefaultId] = useState<string | null>(null);
  const [thumbs, setThumbs] = useState<Record<string, string | null>>({});
  const [previewHtml, setPreviewHtml] = useState("");
  const [loadingPreview, setLoadingPreview] = useState(false);
  const [fullPreviewId, setFullPreviewId] = useState<string | null>(null);

  const defaultTemplateId = savedSettings.defaultTemplateId;
  const selectedTemplate = useMemo(() => templates.find((item) => item.templateId === selectedTemplateId) ?? null, [selectedTemplateId, templates]);
  const fullPreviewTemplate = useMemo(() => templates.find((item) => item.templateId === fullPreviewId) ?? null, [fullPreviewId, templates]);
  const optionsDirty = OPTION_KEYS.some((key) => (settings[key] ?? "") !== (savedSettings[key] ?? ""));

  const loadAll = useCallback(async () => {
    setLoading(true);
    setLoadError(false);
    try {
      const [templateRows, settingsRow] = await Promise.all([getInvoiceTemplates(), getInvoiceTemplateSettings()]);
      const rows = [...templateRows].sort((left, right) => (left.sortOrder ?? 1000) - (right.sortOrder ?? 1000));
      const merged = { ...emptySettings, ...settingsRow, defaultTemplateId: settingsRow.defaultTemplateId || rows[0]?.templateId || "" };
      setTemplates(rows);
      setSavedSettings(merged);
      setSettings(merged);
      setSelectedTemplateId((current) => (current && rows.some((row) => row.templateId === current) ? current : merged.defaultTemplateId));
      setThumbs({});
    } catch (error) {
      setLoadError(true);
      setApiError(error, "Unable to load invoice templates");
    } finally {
      setLoading(false);
    }
  }, [setApiError]);

  useEffect(() => {
    void loadAll();
  }, [loadAll]);

  // Gallery thumbnails: saved options + sample invoice, thode-thode (3 parallel) taaki backend par burst na ho.
  useEffect(() => {
    if (!canPreview || loading || !templates.length) {
      return;
    }
    let cancelled = false;
    const queue = templates.map((item) => item.templateId).filter((templateId) => thumbs[templateId] === undefined);
    const payload = toPreviewRequest(savedSettings);
    const worker = async () => {
      while (!cancelled && queue.length) {
        const templateId = queue.shift() as string;
        try {
          const preview = await previewInvoiceTemplate(templateId, payload);
          if (!cancelled) {
            setThumbs((current) => ({ ...current, [templateId]: preview.html }));
          }
        } catch {
          if (!cancelled) {
            setThumbs((current) => ({ ...current, [templateId]: null }));
          }
        }
      }
    };
    void Promise.all(Array.from({ length: THUMB_CONCURRENCY }, worker));
    return () => {
      cancelled = true;
    };
    // thumbs intentionally omitted: sirf missing wale load karne hain, har set par dobara nahi.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [canPreview, loading, templates, savedSettings]);

  // Live preview: selected template + abhi ke (unsaved) options.
  useEffect(() => {
    if (!canPreview || !selectedTemplateId) {
      return;
    }
    let cancelled = false;
    const timeoutId = window.setTimeout(async () => {
      try {
        setLoadingPreview(true);
        const preview = await previewInvoiceTemplate(selectedTemplateId, toPreviewRequest(settings));
        if (!cancelled) {
          setPreviewHtml(preview.html);
        }
      } catch (error) {
        if (!cancelled) {
          setApiError(error, "Unable to preview invoice template");
        }
      } finally {
        if (!cancelled) {
          setLoadingPreview(false);
        }
      }
    }, 250);
    return () => {
      cancelled = true;
      window.clearTimeout(timeoutId);
    };
  }, [canPreview, selectedTemplateId, settings, setApiError]);

  const setAsDefault = async (templateId: string) => {
    if (!canChangeDefault || templateId === defaultTemplateId) {
      return;
    }
    clearMessage();
    try {
      setSettingDefaultId(templateId);
      // Sirf default badlo: saved options bhejo, form ke unsaved edits nahi.
      const saved = await updateInvoiceTemplateSettings(toSaveRequest(savedSettings, templateId));
      setSavedSettings((current) => ({ ...current, ...saved }));
      setSettings((current) => ({ ...current, defaultTemplateId: saved.defaultTemplateId }));
      setTemplates((current) => current.map((item) => ({ ...item, defaultTemplate: item.templateId === saved.defaultTemplateId })));
      const name = templates.find((item) => item.templateId === templateId)?.templateName ?? "Template";
      notificationService.showSuccess(`${name} is now your default invoice template.`);
    } catch (error) {
      setApiError(error, "Unable to change the default template");
    } finally {
      setSettingDefaultId(null);
    }
  };

  const saveOptions = async () => {
    clearMessage();
    try {
      setSavingOptions(true);
      const saved = await updateInvoiceTemplateSettings(toSaveRequest(settings, defaultTemplateId));
      const merged = { ...emptySettings, ...saved };
      setSavedSettings(merged);
      setSettings(merged);
      setThumbs({});
      notificationService.showSuccess(CommonSuccessMessageUtil.updated("Invoice Print Options"));
    } catch (error) {
      setApiError(error, "Unable to save invoice print options");
    } finally {
      setSavingOptions(false);
    }
  };

  const update = <K extends OptionKey>(key: K, value: CompanyInvoiceSettings[K]) => setSettings((current) => ({ ...current, [key]: value }));

  return (
    <div className="space-y-4 pb-6">
      <Header title="Invoice Templates" subtitle="Pick how your invoices look on print, PDF, email and WhatsApp. Preview every design with sample data and set one as default." />

      <GlassCard className="p-4 md:p-6">
        <div className="flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
          <CommonBreadcrumb items={[{ label: "Setup" }, { label: "Invoice Templates" }]} />
          {!loading && templates.length ? (
            <p className="text-xs font-medium text-slate-500">
              {templates.length} designs · Default: <span className="font-semibold text-slate-800">{templates.find((item) => item.templateId === defaultTemplateId)?.templateName ?? "--"}</span>
            </p>
          ) : null}
        </div>

        {!canPreview ? (
          <InfoNote className="mt-4">You can see the template list, but you do not have permission to preview templates.</InfoNote>
        ) : null}

        {/* Gallery: compact cards, live thumbnail (sample invoice) per template. */}
        <div className="mt-4 grid grid-cols-2 gap-3 sm:grid-cols-3 lg:grid-cols-4 xl:grid-cols-5">
          {loading
            ? Array.from({ length: 10 }).map((_, index) => (
              <div key={index} className="overflow-hidden rounded-xl border border-slate-200 bg-white">
                <div className="animate-pulse bg-slate-100" style={{ height: THUMB_HEIGHT }} />
                <div className="space-y-2 p-3">
                  <div className="h-3.5 w-3/4 animate-pulse rounded bg-slate-100" />
                  <div className="h-3 w-1/2 animate-pulse rounded bg-slate-100" />
                </div>
              </div>
            ))
            : templates.map((template) => (
              <TemplateCard
                key={template.templateId}
                template={template}
                html={thumbs[template.templateId]}
                canPreview={canPreview}
                selected={template.templateId === selectedTemplateId}
                isDefault={template.templateId === defaultTemplateId}
                canChangeDefault={canChangeDefault}
                settingDefault={settingDefaultId === template.templateId}
                onSelect={() => setSelectedTemplateId(template.templateId)}
                onPreview={() => setFullPreviewId(template.templateId)}
                onSetDefault={() => void setAsDefault(template.templateId)}
                onRetry={() => setThumbs((current) => {
                  const next = { ...current };
                  delete next[template.templateId];
                  return next;
                })}
              />
            ))}
        </div>

        {!loading && !templates.length ? (
          <EmptyState
            className="mt-4 rounded-xl border border-dashed border-slate-200"
            icon={<FileText size={24} />}
            title={loadError ? "Invoice templates could not be loaded" : "No invoice templates available"}
            description={loadError ? "Check your connection and reload the page." : "Contact support to enable invoice templates."}
          />
        ) : null}
      </GlassCard>

      {!loading && templates.length ? (
        <div className="grid gap-4 xl:grid-cols-[340px_minmax(0,1fr)]">
          <GlassCard className="min-w-0 p-4 md:p-5">
            <div className="flex items-start justify-between gap-3">
              <div>
                <p className="text-sm font-bold text-slate-900">Print options</p>
                <p className="mt-0.5 text-xs text-slate-500">Apply to every template. The preview updates as you type.</p>
              </div>
              {optionsDirty ? <span className="shrink-0 rounded-full bg-amber-50 px-2 py-0.5 text-[11px] font-semibold text-amber-700">Unsaved</span> : null}
            </div>

            {!canChangeDefault ? (
              <InfoNote className="mt-3">You can try options in the preview, but you do not have rights to save them.</InfoNote>
            ) : null}

            <div className="mt-4 space-y-2.5">
              <OptionGroup title="Payment">
                <Toggle label="Bank details" hint="From company profile" value={settings.showBankDetails} onChange={(value) => update("showBankDetails", value)} />
                <Toggle label="UPI QR code" hint="Needs a UPI ID in company profile" value={settings.showQr} onChange={(value) => update("showQr", value)} />
              </OptionGroup>

              <OptionGroup title="Signature">
                <Toggle label="Authorised signatory" value={settings.showSignature} onChange={(value) => update("showSignature", value)} />
                {settings.showSignature ? (
                  <div className="grid gap-2.5 px-3 pb-3">
                    <Input
                      label="Heading"
                      maxLength={LIMITS.signatureHeading}
                      hint={'"For Company" prints as "For <your company name>"'}
                      value={settings.signatureHeading ?? ""}
                      onChange={(event) => update("signatureHeading", event.target.value)}
                    />
                    <Input label="Label" maxLength={LIMITS.signatureLabel} value={settings.signatureLabel ?? ""} onChange={(event) => update("signatureLabel", event.target.value)} />
                  </div>
                ) : null}
              </OptionGroup>

              <OptionGroup title="Text">
                <Toggle label="Terms & conditions" value={settings.showTerms} onChange={(value) => update("showTerms", value)} />
                {settings.showTerms ? (
                  <TextAreaField label="Terms & conditions" maxLength={LIMITS.termsText} value={settings.termsText ?? ""} onChange={(value) => update("termsText", value)} />
                ) : null}
                <Toggle label="Notes" value={settings.showNotes} onChange={(value) => update("showNotes", value)} />
                {settings.showNotes ? (
                  <TextAreaField label="Notes" maxLength={LIMITS.noteText} value={settings.noteText ?? ""} onChange={(value) => update("noteText", value)} />
                ) : null}
              </OptionGroup>

              <OptionGroup title="Watermark & footer">
                <Toggle label="Watermark" hint="Empty label = PAID / INVOICE automatically" value={settings.showWatermark} onChange={(value) => update("showWatermark", value)} />
                {settings.showWatermark ? (
                  <div className="px-3 pb-3">
                    <Input label="Watermark label" maxLength={LIMITS.watermarkText} placeholder="e.g. ORIGINAL" value={settings.watermarkText ?? ""} onChange={(event) => update("watermarkText", event.target.value)} />
                  </div>
                ) : null}
                <div className="px-3 py-3">
                  <Input label="Footer credit" maxLength={LIMITS.footerCredit} placeholder="Leave empty to hide" value={settings.footerCredit ?? ""} onChange={(event) => update("footerCredit", event.target.value)} />
                </div>
              </OptionGroup>
            </div>

            {canChangeDefault ? (
              <div className="mt-4 flex gap-2">
                <Button type="button" variant="secondary" disabled={!optionsDirty || savingOptions} onClick={() => setSettings({ ...savedSettings })}>
                  <RotateCcw size={15} /> Reset
                </Button>
                <Button type="button" className="flex-1" disabled={!optionsDirty || savingOptions} onClick={() => void saveOptions()}>
                  <Save size={15} /> {savingOptions ? "Saving..." : "Save options"}
                </Button>
              </div>
            ) : null}
          </GlassCard>

          <GlassCard className="min-w-0 p-4 md:p-5">
            <div className="flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
              <div className="min-w-0">
                <p className="text-xs font-semibold uppercase tracking-[0.14em] text-slate-400">Live preview · sample invoice</p>
                <div className="mt-1 flex flex-wrap items-center gap-2">
                  <h3 className="truncate text-lg font-bold text-slate-950">{selectedTemplate?.templateName ?? "Invoice template"}</h3>
                  {selectedTemplate && selectedTemplate.templateId === defaultTemplateId ? <DefaultBadge /> : null}
                </div>
                {selectedTemplate ? <p className="mt-0.5 line-clamp-2 text-xs text-slate-500">{selectedTemplate.description}</p> : null}
              </div>
              <div className="flex shrink-0 flex-wrap gap-2">
                {selectedTemplate && canChangeDefault && selectedTemplate.templateId !== defaultTemplateId ? (
                  <Button type="button" variant="secondary" disabled={settingDefaultId !== null} onClick={() => void setAsDefault(selectedTemplate.templateId)}>
                    <Star size={15} /> {settingDefaultId === selectedTemplate.templateId ? "Setting..." : "Set as default"}
                  </Button>
                ) : null}
                <Button type="button" variant="secondary" disabled={!previewHtml} onClick={() => setFullPreviewId(selectedTemplateId)}>
                  <Maximize2 size={15} /> Full view
                </Button>
                <Button type="button" variant="secondary" disabled={!previewHtml} onClick={() => printHtml(previewHtml)}>
                  <Printer size={15} /> Print
                </Button>
              </div>
            </div>
            {canPreview ? (
              <ScaledPreview html={previewHtml} title={selectedTemplate?.templateName ?? "Invoice preview"} loading={loadingPreview} className="mt-4" maxHeight={760} />
            ) : (
              <EmptyState className="mt-4 rounded-xl border border-dashed border-slate-200" icon={<Eye size={24} />} title="Preview not available" description="Ask an admin for the Invoice Templates preview permission." />
            )}
          </GlassCard>
        </div>
      ) : null}

      <Modal
        open={Boolean(fullPreviewTemplate)}
        title={fullPreviewTemplate?.templateName ?? "Preview"}
        eyebrow={fullPreviewTemplate ? `${fullPreviewTemplate.category ?? "Template"} · ${paperLabel(fullPreviewTemplate)}` : "Preview"}
        maxWidthClass="max-w-5xl"
        onClose={() => setFullPreviewId(null)}
      >
        {fullPreviewTemplate ? (
          <FullPreview
            template={fullPreviewTemplate}
            // Selected template ka live (unsaved options wala) HTML; baaki ka saved-options thumbnail.
            html={fullPreviewTemplate.templateId === selectedTemplateId && previewHtml ? previewHtml : thumbs[fullPreviewTemplate.templateId] ?? ""}
            isDefault={fullPreviewTemplate.templateId === defaultTemplateId}
            canChangeDefault={canChangeDefault}
            settingDefault={settingDefaultId === fullPreviewTemplate.templateId}
            onSetDefault={() => void setAsDefault(fullPreviewTemplate.templateId)}
            onCustomise={() => {
              setSelectedTemplateId(fullPreviewTemplate.templateId);
              setFullPreviewId(null);
            }}
          />
        ) : null}
      </Modal>
    </div>
  );
};

const DefaultBadge = () => (
  <span className="inline-flex items-center gap-1 rounded-full bg-emerald-50 px-2 py-0.5 text-[11px] font-semibold text-emerald-700 ring-1 ring-emerald-200">
    <CheckCircle2 size={12} /> Default
  </span>
);

const TemplateCard = ({
  template,
  html,
  canPreview,
  selected,
  isDefault,
  canChangeDefault,
  settingDefault,
  onSelect,
  onPreview,
  onSetDefault,
  onRetry
}: {
  template: InvoiceTemplateMetadata;
  html: string | null | undefined;
  canPreview: boolean;
  selected: boolean;
  isDefault: boolean;
  canChangeDefault: boolean;
  settingDefault: boolean;
  onSelect: () => void;
  onPreview: () => void;
  onSetDefault: () => void;
  onRetry: () => void;
}) => {
  const boxRef = useRef<HTMLDivElement | null>(null);
  const [boxWidth, setBoxWidth] = useState(0);

  useEffect(() => {
    const box = boxRef.current;
    if (!box || typeof ResizeObserver === "undefined") {
      return;
    }
    const observer = new ResizeObserver((entries) => setBoxWidth(Math.floor(entries[0]?.contentRect.width ?? 0)));
    observer.observe(box);
    return () => observer.disconnect();
  }, []);

  const scale = boxWidth ? boxWidth / A4_WIDTH : 0.25;

  return (
    <div
      className={clsx(
        "group flex min-w-0 flex-col overflow-hidden rounded-xl border bg-white transition",
        selected
          ? "border-[var(--theme-color)] shadow-[0_10px_28px_-16px_color-mix(in_srgb,var(--theme-color)_60%,transparent)] ring-1 ring-[var(--theme-color)]"
          : "border-slate-200 hover:border-slate-300 hover:shadow-sm"
      )}
    >
      <button
        type="button"
        onClick={() => {
          onSelect();
          if (canPreview && html === null) {
            onRetry();
          }
        }}
        aria-pressed={selected}
        aria-label={`Select ${template.templateName}`}
        className="relative block w-full overflow-hidden border-b border-slate-100 bg-slate-50 text-left"
        style={{ height: THUMB_HEIGHT }}
      >
        <div ref={boxRef} className="absolute inset-0">
          {canPreview && html ? (
            <InvoiceFrame html={html} title={`${template.templateName} thumbnail`} width={A4_WIDTH} height={Math.ceil(THUMB_HEIGHT / scale)} scale={scale} />
          ) : canPreview && html === undefined ? (
            <div className="h-full w-full animate-pulse bg-slate-100" />
          ) : (
            // Preview na ho to template ka accent swatch dikhao.
            <div className="flex h-full w-full flex-col justify-between p-3" style={{ background: `linear-gradient(160deg, ${accentOf(template)}1f, #ffffff 70%)` }}>
              <span className="h-2 w-10 rounded-full" style={{ background: accentOf(template) }} />
              <FileText size={28} style={{ color: accentOf(template) }} />
              {canPreview && html === null ? (
                <span className="self-start text-[11px] font-semibold text-slate-500 underline">Preview failed · click to retry</span>
              ) : <span />}
            </div>
          )}
        </div>
        <span className="absolute left-2 top-2 flex flex-wrap gap-1">
          {isDefault ? <DefaultBadge /> : null}
        </span>
        <span className="absolute bottom-2 right-2 rounded-md bg-slate-900/80 px-1.5 py-0.5 text-[10px] font-semibold tracking-wide text-slate-50">{paperLabel(template)}</span>
      </button>

      <div className="flex min-w-0 flex-1 flex-col gap-2 p-3">
        <div className="min-w-0">
          <div className="flex items-center gap-1.5">
            <span className="h-2 w-2 shrink-0 rounded-full" style={{ background: accentOf(template) }} />
            <p className="truncate text-sm font-bold text-slate-900" title={template.templateName}>{template.templateName}</p>
          </div>
          <p className="mt-0.5 truncate text-[11px] font-medium uppercase tracking-[0.08em] text-slate-400">{template.category ?? "Template"}</p>
        </div>
        <div className="mt-auto flex items-center gap-1.5">
          <Button type="button" variant="ghost" className="min-h-8 flex-1 px-2 py-1 text-xs" disabled={!canPreview || !html} onClick={onPreview} title="Full preview">
            <Eye size={14} className="shrink-0" /> Preview
          </Button>
          {canChangeDefault && !isDefault ? (
            <Button type="button" variant="secondary" className="min-h-8 flex-1 px-2 py-1 text-xs" disabled={settingDefault} onClick={onSetDefault} title="Use this template for all invoices">
              <Star size={14} className="shrink-0" /> {settingDefault ? "..." : "Default"}
            </Button>
          ) : null}
        </div>
      </div>
    </div>
  );
};

/** Box ki width ke hisaab se invoice ko scale karta hai; user zoom bhi kar sakta hai. */
const ScaledPreview = ({ html, title, loading, className, maxHeight }: { html: string; title: string; loading: boolean; className?: string; maxHeight: number }) => {
  const boxRef = useRef<HTMLDivElement | null>(null);
  const [boxWidth, setBoxWidth] = useState(0);
  const [zoom, setZoom] = useState<number | null>(null);

  useEffect(() => {
    const box = boxRef.current;
    if (!box || typeof ResizeObserver === "undefined") {
      return;
    }
    const observer = new ResizeObserver((entries) => setBoxWidth(Math.floor(entries[0]?.contentRect.width ?? 0)));
    observer.observe(box);
    return () => observer.disconnect();
  }, []);

  // Invoice kam se kam PREVIEW_MIN_WIDTH par layout ho (phone par right side na kate), fit-to-width scale.
  const layoutWidth = Math.max(A4_WIDTH, PREVIEW_MIN_WIDTH);
  const fitScale = boxWidth ? Math.min(1, boxWidth / layoutWidth) : 0.6;
  const scale = zoom ?? fitScale;
  const frameHeight = Math.round(A4_HEIGHT * 1.25);

  return (
    <div className={className}>
      <div className="mb-2 flex items-center justify-between gap-2">
        <span className={clsx("text-xs font-medium", loading ? "text-[var(--theme-color)]" : "text-slate-400")}>{loading ? "Updating preview..." : "Scroll inside to see the full invoice"}</span>
        <div className="inline-flex items-center gap-1 rounded-full border border-slate-200 bg-white px-1.5 py-0.5">
          <Button type="button" variant="ghost" size="icon-sm" aria-label="Zoom out" disabled={scale <= 0.3} onClick={() => setZoom(Math.max(0.3, Number((scale - 0.1).toFixed(2))))}>
            <ZoomOut size={15} />
          </Button>
          <button type="button" className="min-w-11 text-center text-xs font-bold text-slate-600" title="Fit to width" onClick={() => setZoom(null)}>
            {Math.round(scale * 100)}%
          </button>
          <Button type="button" variant="ghost" size="icon-sm" aria-label="Zoom in" disabled={scale >= 1.6} onClick={() => setZoom(Math.min(1.6, Number((scale + 0.1).toFixed(2))))}>
            <ZoomIn size={15} />
          </Button>
        </div>
      </div>
      <div ref={boxRef} className="scrollbar-thin overflow-auto rounded-lg border border-slate-200 bg-slate-100" style={{ maxHeight }}>
        {html ? (
          <div className={clsx("transition-opacity", loading && "opacity-60")} style={{ width: layoutWidth * scale, height: frameHeight * scale, margin: "0 auto" }}>
            <InvoiceFrame html={html} title={title} width={layoutWidth} height={frameHeight} scale={scale} />
          </div>
        ) : (
          <div className="flex h-64 items-center justify-center text-sm text-slate-400">{loading ? "Loading preview..." : "Select a template to preview"}</div>
        )}
      </div>
    </div>
  );
};

